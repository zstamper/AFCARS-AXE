class MainWindow2Controller:

    def __init__(self):
        self.window = MainWindow2Dialog()
        self.window.setWindowTitle("AFCARS XML Editor")
        self.window.fips_codes = self.get_fips_codes()
        self.window.epa_codes = self.get_epa_codes()
        self.window.reporting_periods = self.get_reporting_periods()
        self.window.report_types = self.get_report_types()
        self.window.file_type = FileType.PRODUCTION
        self.window.on_go = self.do_go

        self.window.on_close = self.save_defaults
        self.window.on_export = self.do_export
        self.window.on_import = self.do_import
        self.window.on_about = self.do_about

    def show(self):
        self.load_defaults()
        return self.window.show()

    def load_defaults(self):
        config = ConfigTable.get_or_none(ConfigTable.id == 1)
        if config:
            self.window.epa_code = [k for k, v in EPA_CODES.items() if v == config.epa_code][
                0] if config.epa_code else None
            self.window.fips_code = [k for k, v in FIPS_CODES.items() if v == config.fips_code][
                0] if config.fips_code else None
            self.window.reporting_period = config.reporting_period
            self.window.report_type = config.report_type
            self.window.file_type = config.file_type

    def save_defaults(self):
        config, _ = ConfigTable.get_or_create(id=1)
        config.epa_code = EPA_CODES[self.window.epa_code] if self.window.epa_code else None
        config.fips_code = FIPS_CODES[self.window.fips_code] if self.window.fips_code else None
        config.reporting_period = self.window.reporting_period
        config.report_type = self.window.report_type
        config.file_type = self.window.file_type
        config.save()

    @staticmethod
    def get_fips_codes() -> list:
        return list(FIPS_CODES.keys())

    @staticmethod
    def get_epa_codes() -> list:
        return list(EPA_CODES.keys())

    @staticmethod
    def get_reporting_periods() -> list[str]:
        return [f"{year}{period}" for year in range(2023, 2036) for period in ['A', 'B']]

    @staticmethod
    def get_report_types() -> list[str]:
        return [e.value for e in ReportType]

    @property
    def agency_code(self) -> str:
        return EPA_CODES[self.window.epa_code] if self.window.epa_code \
            else FIPS_CODES[self.window.fips_code] if self.window.fips_code \
            else None

    def do_go(self, *args, **kwargs):
        controller: ChildController = ChildController(self.window)
        controller.reporting_period = self.window.reporting_period
        controller.report_type = self.window.report_type
        controller.file_type = self.window.file_type
        controller.agency_name = self.window.fips_code if self.window.fips_code \
            else self.window.epa_code if self.window.epa_code \
            else ""
        controller.e1 = self.e1
        set_E1(self.e1)
        set_E2(self.window.reporting_period)
        try:
            controller.show()
        except Exception as e:
            print(f"Exception {e.__class__.__name__}({', '.join(e.args)})")
            traceback.print_exc()
            raise e

    @property
    def e1(self) -> str:
        return FIPS_CODES[self.window.fips_code] if self.window.fips_code in FIPS_CODES \
            else EPA_CODES[self.window.epa_code] if self.window.epa_code in EPA_CODES \
            else ""

    def do_export(self):
        controller: ExportController = ExportController(self.window)
        controller.e1 = self.e1
        controller.e2 = self.window.reporting_period
        controller.report_type = self.window.report_type
        controller.file_type = self.window.file_type
        controller.show()

    def do_import(self):
        controller: ImportController = ImportController(self.window)
        controller.show()

    def do_about(self):
        controller = AboutController(self.window)
        controller.exec()
